'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync(require('node:path').join(__dirname, '..', 'furnace-engine.js'), 'utf8');
const context = {window: {}};
vm.runInNewContext(source, context, {filename: 'furnace-engine.js'});
const create = () => context.window.MineWorldFurnace.create();
const at = (x, y=-64) => ({dimension:'overworld', x, y, z:3});
test('switching an ignited furnace to a smoker preserves remaining fuel capacity and items', () => {
 const e=create(), p=at(11);
 e.ensure(p,'furnace');
 assert.equal(e.insert(p,'input','raw',8),8);
 assert.equal(e.insert(p,'fuel','coal',1),1);
 assert.equal(e.tick(10).completed,1);
 const before=e.status(p);
 assert.equal(before.burnSecondsRemaining,70);
 e.ensure(p,'smoker');
 const after=e.status(p);
 assert.equal(after.burnSecondsRemaining,35);
 assert.equal(after.input.qty,7);
 assert.equal(after.output.qty,1);
 assert.equal(e.tick(35).completed,7);
 assert.equal(e.status(p).output.qty,8);
 assert.equal(e.status(p).burnSecondsRemaining,0);
});
test('switching an ignited smoker to a furnace does not create extra smelts', () => {
 const e=create(), p=at(12);
 e.ensure(p,'smoker');
 e.insert(p,'input','raw',8);
 e.insert(p,'fuel','coal',1);
 assert.equal(e.tick(5).completed,1);
 e.ensure(p,'furnace');
 assert.equal(e.status(p).burnSecondsRemaining,70);
 assert.equal(e.tick(60).completed,6);
 assert.equal(e.tick(10).completed,1);
 assert.equal(e.status(p).output.qty,8);
 assert.equal(e.status(p).burnSecondsRemaining,0);
});
test('station conversion resets incompatible partial cooking without losing stacks', () => {
 const e=create(), p=at(13);
 e.ensure(p,'furnace');
 e.insert(p,'input','rawIron',2);
 e.insert(p,'fuel','coal',1);
 e.tick(4);
 assert.ok(e.status(p).progress>0);
 e.ensure(p,'smoker');
 assert.equal(e.status(p).progress,0);
 assert.equal(e.status(p).idleReason,'no_recipe');
 assert.equal(e.take(p,'input',2).qty,2);
 assert.equal(e.status(p).burnSecondsRemaining,38);
});
